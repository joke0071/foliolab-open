import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:820}});
try{
 await page.goto('http://127.0.0.1:4173/');
 const ids=await page.evaluate(async()=>{
  const {blankModel,createProvider,createAccount,createPosition,persist}=await import('/src/model.js');
  const m=blankModel(),provider=createProvider({name:'Musterbroker',type:'broker'});
  m.providers.push(provider);
  const account=createAccount({name:'Depot',providerId:provider.id,type:'securities'},m);m.accounts.push(account);
  const add=(name,kind,symbol,isin,exchange)=>{
   const p=createPosition({providerId:provider.id,accountId:account.id,kind,name,symbol,isin,exchange,quantity:3,price:40,currency:'EUR'},m);
   m.positions.push(p);return p.id;
  };
  const relevant=add('Alpha Kurskennung','etf','','IE00B3RBWM25','Xetra');
  const optional=add('Beta Optionale ISIN','stock','BETA','','Xetra');
  const complete=add('Gamma Vollständig','fund','GAMMA','IE00B3RBWM25','Xetra');
  const crypto=add('Delta Bitcoin','crypto','BTC','','');
  for(let i=0;i<52;i++)add('Zusatzposition '+String(i+1).padStart(2,'0'),'etf','ETF'+i,'','Xetra');
  persist(m);return {relevant,optional,complete,crypto};
 });
 await page.reload();
 await page.locator('#mobileNav [data-page="positions"]').click();
 const trigger=page.locator('#resolveListings'),panel=page.locator('#listingReviewPanel');
 assert.equal(await page.locator('#listingReviewAction').isVisible(),true);
 assert.equal(await trigger.getAttribute('aria-expanded'),'false');
 assert.equal(await panel.isVisible(),false);
 assert.match(await trigger.innerText(),/Positionen ansehen \(54\)/);
 const intro=await page.locator('#listingReviewIntro').innerText();
 assert.match(intro,/54 Wertpapierpositionen mit fehlenden Angaben/);
 assert.match(intro,/1 mit möglicherweise kursrelevanten Kennungen/);
 assert.match(intro,/53 nur ohne ISIN \(optional\)/);
 assert.match(intro,/nicht automatisch Fehler/);
 assert.equal(await page.locator('#positionList .position-entry').count(),56,'Original positions still visible');
 const before=await page.evaluate(()=>localStorage.getItem('foliolab-open-v1'));
 await trigger.click();
 assert.equal(await trigger.getAttribute('aria-expanded'),'true');
 assert.equal(await panel.isVisible(),true);
 assert.equal(await panel.getAttribute('role'),'region');
 assert.equal(await panel.getAttribute('aria-labelledby'),'listingReviewHeading');
 assert.match(await panel.innerText(),/Eine ISIN ist optional/);
 assert.equal(await panel.locator('.listing-review-item').count(),50);
 assert.equal(await panel.locator('.listing-review-relevant').count(),1);
 assert.equal(await panel.locator('.listing-review-optional').count(),49);
 assert.match(await panel.locator('.listing-review-item').first().innerText(),/Alpha Kurskennung/);
 assert.match(await panel.locator('.listing-review-item').first().innerText(),/Ticker\/Symbol/);
 assert.equal(await panel.getByText('Gamma Vollständig').count(),0);
 assert.equal(await panel.getByText('Delta Bitcoin').count(),0);
 assert.equal(await page.locator('#positionFilters [data-filter="__review"]').count(),1,'Course-quality review is a separate filter');
 await panel.locator('[data-action="more-listing-review"]').click();
 assert.equal(await panel.locator('.listing-review-item').count(),54);
 assert.equal(await panel.locator('.listing-review-optional').count(),53);
 assert.equal(await page.evaluate(()=>localStorage.getItem('foliolab-open-v1')),before,'Showing list cannot modify portfolio');
 await trigger.click();
 assert.equal(await trigger.getAttribute('aria-expanded'),'false');
 assert.equal(await panel.isVisible(),false);
 await trigger.click();
 await panel.locator('[data-action="edit-position"][data-id="'+ids.relevant+'"]').click();
 assert.equal(await page.locator('#dialogTitle').innerText(),'Position bearbeiten');
 assert.equal(await page.locator('[name="symbol"]').inputValue(),'');
 assert.equal(await page.locator('#securityGroup').getAttribute('open'),null,'Does not silently start online security search');
 await page.locator('[name="symbol"]').fill('ALPHA');
 await page.locator('#saveDialog').click();
 await page.locator('#editDialog').waitFor({state:'hidden'});
 assert.match(await trigger.innerText(),/Positionen ansehen \(53\)|Übersicht schließen/);
 assert.match(await page.locator('#listingReviewIntro').innerText(),/53 nur ohne ISIN \(optional\)/);
 assert.equal(await panel.locator('[data-action="edit-position"][data-id="'+ids.relevant+'"]').count(),0);
 await panel.locator('[data-action="edit-position"][data-id="'+ids.optional+'"]').click();
 assert.equal(await page.locator('[name="isin"]').inputValue(),'');
 await page.locator('[name="isin"]').fill('IE00B3RBWM25');
 await page.locator('#saveDialog').click();
 await page.locator('#editDialog').waitFor({state:'hidden'});
 assert.match(await page.locator('#listingReviewIntro').innerText(),/52 Wertpapierpositionen/);
 const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('foliolab-open-v1')).positions);
 assert.equal(after.find(p=>p.id===ids.relevant).symbol,'ALPHA');
 assert.equal(after.find(p=>p.id===ids.relevant).quantity,3);
 assert.equal(after.find(p=>p.id===ids.relevant).price,40);
 assert.equal(after.find(p=>p.id===ids.optional).isin,'IE00B3RBWM25');
 assert.equal(after.length,56,'No positions added or deleted');
 for(const width of [320,360,390,430,768,1024,1440]){
  await page.setViewportSize({width,height:760});
  const geom=await page.locator('#listingReviewAction').evaluate(el=>{
   const b=el.getBoundingClientRect();return {left:b.left,right:b.right,documentWidth:document.documentElement.scrollWidth};
  });
  assert.ok(geom.left>=-1&&geom.right<=width+1&&geom.documentWidth<=width+1,'No horizontal overflow at '+width+': '+JSON.stringify(geom));
 }
 console.log('LISTING REVIEW UX: 54 metadata items, optional vs quote-relevant, paginated list, explicit edits, persistence, seven viewports PASS');
}finally{await browser.close();}
