import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:850}});
try{
 await page.goto('http://127.0.0.1:4173/');
 await page.locator('#mobileNav [data-page="positions"]').click();
 assert.equal(await page.locator('#addPosition').count(),0,'No redundant advanced toolbar action');
 await page.locator('#addWizard').click();
 assert.match(await page.locator('#wizardTitle').innerText(),/Position hinzufügen/);
 assert.equal(await page.locator('.wizard-progress').count(),0,'No unexplained step bubbles');
 assert.equal(await page.locator('#wizardAdvanced').count(),1,'Advanced wallet features remain available');
 assert.equal(await page.locator('#wizardMatches').innerText(),'','No catalog warning before search');
 await page.locator('#wizardProvider').selectOption('__new__');
 await page.locator('#wizardProviderName').fill('Example Broker');
 await page.locator('#wizardAccountName').fill('Wertpapierdepot');
 await page.locator('#wizardQuery').fill('VWCE');
 assert.equal(await page.locator('[data-wizard-pick]').count(),0,'No built-in ETF samples');
 await page.locator('#wizardName').fill('Vanguard FTSE All-World UCITS ETF');
 await page.locator('#wizardSymbol').fill('VWCE');
 await page.locator('#wizardIsin').fill('IE00BK5BQT80');
 await page.locator('#wizardQuantity').fill('1.2345');
 assert.match(await page.locator('#wizardName').inputValue(),/Vanguard/);
 assert.equal(await page.locator('#wizardIsin').inputValue(),'IE00BK5BQT80');
 await page.locator('#wizardNext').click();
 assert.match(await page.locator('#wizardTitle').innerText(),/Anlage hinzugefügt/);
 let state=await page.evaluate(()=>JSON.parse(localStorage.getItem('foliolab-open-v1')));
 assert.equal(state.positions.length,1);
 assert.equal(state.positions[0].quantityExact,'1.2345');
 assert.equal(state.positions[0].costBasisEUR,null);
 assert.equal(state.bookings.length,0);
 await page.locator('#wizardPortfolio').click();
 await page.locator('#addWizard').click();
 await page.locator('#wizardAdvanced > summary').click();
 assert.equal(await page.locator('#wizardDialog').isVisible(),true,'Advanced settings remain in original modal');
 assert.equal(await page.locator('#editDialog').isVisible(),false,'No second editor opens');
 await page.locator('#wizardCostBasis').fill('250');
 await page.locator('#wizardNotes').fill('Notiz bleibt beim Anlegen');
 await page.locator('#wizardKind').selectOption('stock');
 assert.equal(await page.locator('#wizardAdvanced').getAttribute('open'),'');
 assert.equal(await page.locator('#wizardNotes').inputValue(),'Notiz bleibt beim Anlegen');
 await page.locator('#wizardKind').selectOption('stock');
 await page.locator('#wizardName').fill('Synthetic Equity');
 await page.locator('#wizardSymbol').fill('SYN');
 const prov=await page.locator('#wizardProvider option').allTextContents();
 assert.ok(prov.some(s=>s.includes('Example Broker')));
 const providerId=state.providers[0].id,accountId=state.accounts[0].id;
 await page.locator('#wizardProvider').selectOption(providerId);
 await page.locator('#wizardAccount').selectOption(accountId);
 await page.locator('[name=wizardMode][value=buy]').check();
 await page.locator('#wizardQuantity').fill('2');
 await page.locator('#wizardUnitPrice').fill('100');
 await page.locator('#wizardFee').fill('5');
 await page.locator('#wizardNext').click();
 state=await page.evaluate(()=>JSON.parse(localStorage.getItem('foliolab-open-v1')));
 assert.equal(state.bookings.length,1);
 assert.equal(state.journalEntries.length,1);
 assert.equal(state.positions.length,2);
 assert.equal(state.positions[1].costBasisExact,'205');
 await page.locator('#wizardPortfolio').click();
 for(const width of [320,390,430,768,1024,1280,1440]){
  await page.setViewportSize({width,height:820});
  const nav=await page.locator('#mobileNav').isVisible()?'#mobileNav':'#sidebarNav';
  await page.locator(nav+' [data-page="positions"]').click();
  await page.locator('#addWizard').click();
  const scroll=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
  assert.ok(scroll<=1,'Wizard horizontal overflow '+width+'px: '+scroll);
  await page.locator('#wizardPrev').click();
 }
 console.log('ASSET WIZARD: single step, new broker/account, opening balance, purchase ledger, responsive widths PASS');
}finally{await browser.close();}
