import assert from 'node:assert/strict';
import {controlledStorageFixture} from './browser-controlled-storage-fixture.mjs';
import {chromium,firefox,webkit} from 'playwright';
import {mkdirSync} from 'node:fs';
const engine=process.env.UI_PERIOD_ENGINE||'chromium';
const browser=await({chromium,firefox,webkit})[engine].launch({headless:true,args:engine==='chromium'?['--no-sandbox']:[]});
const page=await browser.newPage({viewport:{width:390,height:850}});
mkdirSync('artifacts/gates/ui-visual01',{recursive:true});
const day=n=>new Date(Date.now()-n*864e5).toISOString().slice(0,10);
const record=()=>page.evaluate(async()=>{const {openPortfolioDB,readPortfolioRecord}=await import('/src/atomic-storage.js');const db=await openPortfolioDB();try{return await readPortfolioRecord(db);}finally{db.close();}});
try{
 await page.goto('http://127.0.0.1:4173/');
 await controlledStorageFixture(page,()=>page.waitForFunction(()=>document.getElementById('portfolioStorageState')?.textContent.includes('IndexedDB aktiv')),record);
 await page.evaluate(async(points)=>{
  const {blankModel,createProvider,createAccount,createPosition}=await import('/src/model.js');
  const {PortfolioStorage}=await import('/src/browser-portfolio-storage.js');
  const m=blankModel(),provider=createProvider({name:'Synthetic ETF Portfolio'});m.providers.push(provider);
  m.settings.autoRefresh=false;
  const account=createAccount({name:'Testdepot',providerId:provider.id},m);m.accounts.push(account);
  const p=createPosition({id:'long-price',name:'Historic ETF',kind:'etf',symbol:'VWCE',currency:'EUR',
    quantity:2,price:100,providerId:provider.id,accountId:account.id},m);
  m.positions.push(p);
  m.priceHistories[p.id]={source:'CSV (selbst geprüft)',currency:'EUR',
   points};
  const storage=new PortfolioStorage();await storage.initialize();await storage.save(m);storage.close();
 },[{date:day(2200),total:50},...Array.from({length:1826},(_,i)=>({date:day(1825-i),total:90+i/200}))]);
 await page.reload();
 await page.waitForFunction(()=>document.getElementById('portfolioStorageState')?.textContent.includes('IndexedDB aktiv'));
 const provider=page.locator('#providerOverview .provider-accordion').first();
 await provider.locator(':scope > summary').click();
 const holding=page.locator('#providerOverview [data-position-id="long-price"]');
 await holding.locator(':scope > summary').click();
 await holding.locator('.position-history-chart .chart-plot').waitFor();
 const before=await record();
 assert.ok(before?.raw&&Number.isInteger(before.revision),'the fixture must have an actual canonical IndexedDB record');
 const short=holding.locator('.position-period-presets button');
 const more=holding.locator('.position-period-more > summary');
 const additional=holding.locator('.position-period-extended');
 const chart=holding.locator('.position-history-chart .chart-plot');
 const csv=holding.locator('.position-csv-import');
 const targetGeometry=locator=>locator.evaluateAll(els=>els.map(el=>{
  const r=el.getBoundingClientRect();return {width:r.width,height:r.height,left:r.left,right:r.right,top:Math.round(r.top)};
 }));
 for(const width of [320,360,390,430,768,1024,1440]){
  await page.setViewportSize({width,height:850});
  assert.equal(await holding.locator('.position-period').getAttribute('aria-label'),'Zeitraum des Kursverlaufs');
  assert.deepEqual(await short.allTextContents(),['7 T','1 M','3 M','6 M','1 J']);
  assert.equal(await csv.isVisible(),false);
  const row=await targetGeometry(holding.locator('.position-period-presets button, .position-period-more > summary'));
  assert.equal(new Set(row.map(r=>r.top)).size,1,'period and menu controls fit one row at '+width);
  assert.ok(row.every(r=>r.width>=44&&r.height>=44&&r.left>=0&&r.right<=width+1),'primary targets fit and reach 44px at '+width);
  await more.click();
  assert.deepEqual(await additional.locator('button:visible').allTextContents(),['3 J','5 J','Max']);
  const menu=await targetGeometry(holding.locator('.position-period-popover button:visible'));
  assert.ok(menu.every(r=>r.width>=44&&r.height>=44&&r.left>=0&&r.right<=width+1),'menu targets fit and reach 44px at '+width);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'page width at '+width);
  await page.screenshot({path:'artifacts/gates/ui-visual01/'+engine+'-emulated-'+width+'.png'});
  await more.click();
 }
 await page.setViewportSize({width:390,height:850});
 await short.last().focus();
 await page.keyboard.press('Tab');
 assert.equal(await more.evaluate(el=>el===document.activeElement),true,'Tab reaches the additional range control');
 await page.keyboard.press('Enter');
 assert.equal(await holding.locator('.position-period-more').getAttribute('open'),'');
 const summaryFocus=await more.evaluate(el=>({visible:el.matches(':focus-visible'),width:getComputedStyle(el).outlineWidth}));
 assert.ok(summaryFocus.visible&&summaryFocus.width==='3px');
 const threeYear=additional.locator('[data-position-range="1096"]');
 await page.keyboard.press('Tab');
 const optionFocus=await threeYear.evaluate(el=>({focused:el===document.activeElement,visible:el.matches(':focus-visible'),width:getComputedStyle(el).outlineWidth}));
 assert.ok(optionFocus.focused&&optionFocus.visible&&optionFocus.width==='3px');
 await page.keyboard.press('Enter');
 assert.equal(await threeYear.getAttribute('aria-pressed'),'true');
 assert.equal(await more.evaluate(el=>el===document.activeElement),true);
 assert.match(await more.getAttribute('aria-label'),/3 J ausgewählt/);
 const endpoints=async()=>chart.evaluate(el=>[el.closest('.chart-interactive').querySelector('.chart-x-labels span:first-child').textContent,el.closest('.chart-interactive').querySelector('.chart-x-labels span:last-child').textContent]);
 const labelFormat=new Intl.DateTimeFormat('de-AT',{day:'2-digit',month:'short',year:'numeric',timeZone:'UTC'});
 const dateLabel=date=>labelFormat.format(new Date(date+'T12:00:00Z'));
 assert.deepEqual(await endpoints(),[await dateLabel(day(1095)),await dateLabel(day(0))]);
 await more.click();
 const fiveYear=additional.locator('[data-position-range="1826"]');
 await fiveYear.click();
 assert.equal(await fiveYear.getAttribute('aria-pressed'),'true');
 assert.match(await more.getAttribute('aria-label'),/5 J ausgewählt/);
 assert.deepEqual(await endpoints(),[await dateLabel(day(1825)),await dateLabel(day(0))]);
 await more.click();
 const max=additional.locator('[data-position-range="max"]');
 await max.click();
 assert.equal(await max.getAttribute('aria-pressed'),'true');
 assert.deepEqual(await endpoints(),[await dateLabel(day(2200)),await dateLabel(day(0))]);
 assert.match(await holding.innerText(),/Fehlende Kurse werden nicht ergänzt/);
 assert.equal(await chart.locator('svg path[fill="none"]').count(),1);
 assert.match(await chart.locator('svg path[fill="none"]').getAttribute('d'),/^M[\d. ]+M/,'uncovered space breaks the line');
 await more.click();
 await csv.focus();
 await page.keyboard.press('Escape');
 assert.equal(await more.evaluate(el=>el===document.activeElement),true,'Escape returns to the previous focus target');
 assert.equal(await csv.isVisible(),false);
 assert.equal(JSON.parse((await record()).raw).priceHistories['long-price'].points.length,1827);
 assert.deepEqual(await record(),before,'period changes preserve exact IndexedDB record/settings/revision');
 console.log(engine+': EXTENDED CHART PERIODS: evidenced 3Y/5Y/Max, source boundaries, menu focus, 320–1440px, and exact IndexedDB PASS');
}finally{await browser.close();}
