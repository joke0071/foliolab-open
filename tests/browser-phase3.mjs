import {legacyPage} from './legacy-browser-fixture.mjs';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await legacyPage(browser);
try{
 await page.goto('http://127.0.0.1:4173/');
 const ids=await page.evaluate(async()=>{
  const {blankModel,createProvider,createAccount,createPosition,persist}=await import('/src/model.js');
  const m=blankModel(),provider=createProvider({name:'Testbank'});m.providers.push(provider);
  const dep=createAccount({providerId:provider.id,name:'Depot',type:'securities'},m);
  const bank=createAccount({providerId:provider.id,name:'Verrechnung',type:'checking'},m);m.accounts.push(dep,bank);
  const etf=createPosition({providerId:provider.id,accountId:dep.id,kind:'etf',name:'ETF',isin:'IE00BK5BQT80',symbol:'VWCE',quantity:0,price:100},m);
  const cash=createPosition({providerId:provider.id,accountId:bank.id,kind:'cash',name:'Cash',quantity:3000,price:1},m);
  const staking=createPosition({providerId:provider.id,accountId:dep.id,kind:'crypto',name:'Stakingderivat',symbol:'stETH',quantity:1,price:300},m);
  m.positions.push(etf,cash,staking);persist(m);
  return {etf:etf.id,cash:cash.id,staking:staking.id};
 });
 await page.reload();
 await page.locator('#sidebarNav [data-page="bookings"]').click();
 await page.locator('#openCSVImport').click();
 await page.locator('#csvFile').setInputFiles({name:'historie.csv',mimeType:'text/csv',buffer:Buffer.from('Datum;Typ;ISIN;Menge;Kurs;Gebühr;Steuer\n2026-10-21;Kauf;IE00BK5BQT80;10;100;5;0')});
 await page.locator('#csvCashPosition').evaluate(el=>el.closest('details').open=true);
 await page.locator('#csvCashPosition').selectOption(ids.cash);
 await page.waitForFunction(()=>document.querySelector('#csvReview').textContent.includes('1 bereit'));
 assert.equal(await page.locator('#saveDialog').isDisabled(),false);
 await page.locator('#saveDialog').click();await page.waitForFunction(()=>!document.getElementById('saveDialog').disabled);
 const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('foliolab-open-v1')));
 assert.equal(state.positions.find(p=>p.id===ids.etf).quantityExact,'10');
 assert.equal(state.positions.find(p=>p.id===ids.cash).quantityExact,'1995');
 assert.equal(state.journalEntries.length,1);
 assert.equal(state.bookings[0].importFingerprint!=null,true);
 await page.locator('#openCSVImport').click();
 await page.locator('#csvFile').setInputFiles({name:'historie.csv',mimeType:'text/csv',buffer:Buffer.from('Datum;Typ;ISIN;Menge;Kurs;Gebühr;Steuer\n2026-10-21;Kauf;IE00BK5BQT80;10;100;5;0')});
 await page.waitForFunction(()=>document.querySelector('#csvReview').textContent.includes('1 bereits vorhanden'));
 assert.equal(await page.locator('#saveDialog').isDisabled(),true);
 page.once('dialog',d=>d.accept()); // Discard the staged duplicate CSV preview.
 await page.locator('#cancelDialog').click();
 await page.locator('#sidebarNav [data-page="positions"]').click();
 await page.locator('[data-action="edit-position"][data-id="'+ids.staking+'"]').click();
 await page.locator('#defiPosition').evaluate(el=>el.open=true);
 await page.locator('#editorForm [name="economicRole"]').selectOption('liquid-staking');
 await page.locator('#editorForm [name="valuationMode"]').selectOption('excluded');
 await page.locator('#editorForm [name="representedByPositionId"]').selectOption(ids.etf);
 await page.locator('#saveDialog').click();await page.waitForFunction(()=>!document.getElementById('saveDialog').disabled);
 const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('foliolab-open-v1')));
 assert.equal(after.positions.find(p=>p.id===ids.staking).valuationMode,'excluded');
 assert.equal(after.positions.find(p=>p.id===ids.staking).representedByPositionId,ids.etf);
 await page.locator('#sidebarNav [data-page="dashboard"]').click();
 assert.match(await page.locator('#totalValue').innerText(),/2.995/);
 console.log('Phase 3 browser: CSV preview, atomic balance, duplicate suppression, DeFi exclusion and saved ledger PASS');
}finally{await browser.close();}
