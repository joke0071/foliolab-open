import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:820}});
try{
 await page.goto('http://127.0.0.1:4173/');
 const ids=await page.evaluate(async()=>{
  const {blankModel,persist,createProvider,createAccount,createPosition}=await import('/src/model.js');
  const m=blankModel(),p=createProvider({name:'Flatex',type:'broker'});
  m.providers.push(p);
  const dep=createAccount({providerId:p.id,name:'Depot',type:'securities'},m);
  const cashAcc=createAccount({providerId:p.id,name:'Girokonto',type:'checking'},m);
  m.accounts.push(dep,cashAcc);
  const eur=createPosition({providerId:p.id,accountId:dep.id,kind:'etf',name:'EUR ETF',symbol:'EURT',quantity:10,price:100,currency:'EUR'},m);
  const usd=createPosition({providerId:p.id,accountId:dep.id,kind:'stock',name:'USD Aktie',symbol:'USDT',quantity:5,price:100,currency:'USD',fxRate:0.92},m);
  const cash=createPosition({providerId:p.id,accountId:cashAcc.id,kind:'cash',name:'Giro EUR',quantity:5000,price:1,currency:'EUR'},m);
  m.positions.push(eur,usd,cash);persist(m);
  return {eur:eur.id,usd:usd.id,cash:cash.id};
 });
 await page.reload();
 await page.locator('#mobileNav [data-page="bookings"]').click();
 await page.locator('#addBooking').click();
 assert.match(await page.locator('#dialogTitle').innerText(),/Buchung hinzufügen/);
 assert.equal(await page.locator('#bookingFxWrap').isVisible(),false,'EUR hides reference rate inputs');
 assert.equal(await page.locator('#bookingCash').inputValue(),'','No arbitrary clearing account');
 assert.equal(await page.locator('#bookingPosition').inputValue(),'','Multiple positions require explicit choice');
 assert.equal(await page.locator('#bookingPosition').evaluate(el=>el.checkValidity()),false,'A source position is required');
 assert.equal(await page.locator('#bookingQuantityWrap [name="unitPrice"]').inputValue(),'','No invented trade execution price');
 assert.equal(await page.locator('#bookingQuantityWrap [name="unitPrice"]').getAttribute('required'),'','Trade price required');
 assert.equal(await page.locator('#bookingAdvanced').isVisible(),true,'Trade fees remain reachable');
 await page.locator('#bookingPosition').selectOption(ids.usd);
 assert.equal(await page.locator('#bookingFxWrap').isVisible(),true,'Foreign currency exposes conversion');
 assert.equal(await page.locator('[name="fxRate"]').inputValue(),'','Historical rate must not be guessed');
 await page.locator('#bookingType').selectOption('transfer');
 assert.equal(await page.locator('#bookingTarget').inputValue(),'','Transfer target must not be guessed');
 assert.equal(await page.locator('#bookingTarget').evaluate(el=>el.checkValidity()),false);
 await page.locator('#bookingType').selectOption('split');
 assert.equal(await page.locator('#bookingQuantityWrap').isVisible(),false,'Split hides purchase quantity');
 assert.equal(await page.locator('[name="quantity"]').inputValue(),'0','Metadata events have neutral quantity');
 await page.locator('#bookingType').selectOption('buy');
 assert.equal(await page.locator('#bookingQuantityWrap [name="unitPrice"]').inputValue(),'');
 page.once('dialog',d=>d.accept()); // Explicitly discard changed booking choices.
 await page.locator('#cancelDialog').click();
 await page.locator('#mobileNav [data-page="positions"]').click();
 await page.locator('#addWallet').click();
 assert.match(await page.locator('#dialogTitle').innerText(),/Wallet hinzufügen/);
 assert.equal(await page.locator('#scanProvider').inputValue(),'__new__','Broker must not be mistaken for a wallet');
 assert.equal(await page.locator('#saveDialog').isDisabled(),true,'No import without scan');
 assert.equal(await page.locator('#scanSaveSettings').isVisible(),false,'Storage fields shown only after scan');
 assert.equal(await page.locator('#walletStakingOptions').getAttribute('open'),null,'Staking optional by default');
 await page.locator('#scanAddress').fill('0xd8dA6BF26964aF9D7eEd9e03E53415D37aA96045');
 assert.equal(await page.locator('#saveDialog').isDisabled(),true);
 await page.locator('#walletStakingOptions').evaluate(el=>el.open=true);
 assert.equal(await page.locator('#scanAsset option').count(),51,'Full staking catalog preserved');
 await page.locator('#scanAsset').selectOption('13');
 assert.equal(await page.locator('#scanWalletButton').isDisabled(),true,'Unsupported staking remains blocked');
 await page.locator('#scanAsset').selectOption('');
 assert.equal(await page.locator('#scanWalletButton').isDisabled(),false);
 console.log('MODAL CLARITY: booking fields, no invented FX/price or cash link, wallet gating, provider and staking PASS');
}finally{await browser.close();}
